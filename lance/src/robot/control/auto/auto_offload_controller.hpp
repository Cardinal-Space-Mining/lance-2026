#pragma once

#include "robot/core/robot_params.hpp"
#include "robot/core/motor_interface.hpp"
#include "robot/control/shared/shared_controllers.hpp"
#include "robot/planning/offload_planner.hpp"


namespace lance
{
using Vec2f = Eigen::Vector2f;

class AutoOffloadController
{
    friend class TelemetrySerializer;
    friend class TelemetryDeserializer;

public:
    AutoOffloadController(const RobotParams&, SharedControllerCollection&);
    ~AutoOffloadController() = default;

public:
    void initialize();
    bool isFinished();
    void setCancelled();

    void iterate(
        const RobotMotorStatus& motor_status,
        RobotMotorCommands& commands);

private:
    Vec2f determineDir();

protected:
    enum class Stage
    {
        INITIALIZATION,
        PLANNING,
        TRAVERSING,
        OFFLOADING,
        FINISHED
    };
    enum class Direction
    {
        UP,
        DOWN,
        LEFT,
        RIGHT
    };

protected:
    const RobotParams& params;

    TraversalController& traversal_controller;
    OffloadController& offload_controller;

    size_t idx = 0;
    // Vector containing all planned offload actions to be executed in order
    std::vector<OffloadPlanner::OffloadAction> plan;

    Stage stage{Stage::FINISHED};
};

};  // namespace lance
